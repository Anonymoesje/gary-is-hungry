// node build.js
// 1. Wraps index.html (written for the claude.ai artifact) into a normal page for GitHub Pages: docs/index.html
// 2. Copies the game's physics and course code into the leaderboard worker: worker/src/sim.js
const fs = require('fs');
const path = require('path');

const body = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');
// The page only ever talks to Google Fonts and the leaderboard worker, so the policy says exactly that.
const csp = [
  "default-src 'none'",
  "script-src 'unsafe-inline'",
  "style-src 'unsafe-inline' https://fonts.googleapis.com",
  'font-src https://fonts.gstatic.com',
  'connect-src https://gary-board.anonymoesje.workers.dev',
  "img-src 'self' data:",
  "base-uri 'none'",
  "form-action 'none'",
].join('; ');
const head = '<!doctype html><html lang="en"><head><meta charset="utf-8">'
  + '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
  + '<meta http-equiv="Content-Security-Policy" content="' + csp + '">'
  + '<meta name="referrer" content="no-referrer">'
  + '<style>[hidden]{display:none!important}img{max-width:100%}</style></head><body>';
fs.mkdirSync(path.join(__dirname, 'docs'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'docs', 'index.html'), head + body + '</body></html>\n');
console.log('wrote docs/index.html');

const sim = /\/\* SIM BEGIN[^\n]*\n([\s\S]*?)\/\* SIM END \*\//.exec(body);
if (!sim) throw new Error('SIM BEGIN / SIM END markers not found in index.html');
fs.mkdirSync(path.join(__dirname, 'worker', 'src'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'worker', 'src', 'sim.js'),
  '// Generated by build.js from index.html. Edit the game, then run node build.js.\n'
  + sim[1]
  + 'export { SIM, Course, simulateGhost, decodeFlips, encodeFlips, cleanName };\n');
console.log('wrote worker/src/sim.js');
